/**
 * Абстракция доступа к данным словаря.
 *
 * UI знает только этот модуль; конкретная реализация (SQLite в браузере,
 * REST API и т.п.) выбирается в src/db/index.ts.
 */

/** Строка таблицы forms. */

/** Одна запись из general.prepositions (заполняется ollama, см. llm/fill_prepositions.py). */
export interface PrepositionEntry {
  /** Сам предлог на иврите, например "על". */
  prep: string;
  /** Пример сочетания «глагол + предлог» на иврите. */
  example: string;
  /** Короткий русский комментарий к значению сочетания. */
  comment: string;
}

export interface FormRow {
  /** Форма слова с огласовками, например "אָבִּים". */
  word: string;
  /** Часть речи (en); null — сайт не указал (יֵשׁ, אֵין). */
  pos: string | null;
  /** Биньян (только для глаголов); null — не применимо. */
  binyan: string | null;
  /** Каноническая страница, например "6074-lehaavid". */
  canonical: string;
  /** Тот же word без огласовок — поле поиска. */
  no_nikud: string;
  /** Грамматика формы: {number: "Единственное число", ...}; null — у лемм без таблиц. */
  form: Record<string, string> | null;
  /** Русская транскрипция с ударением (апостроф); null если отсутствует. */
  transcription: string | null;
  /** Русский перевод. */
  translation: string;
  /** Корень слова (без огласовок), например "אבב"; "" — сайт не указал. */
  root: string;
  /** Примечания о корне/слове; "" — отсутствуют. */
  description: string;
  /**
   * Строка найдена дополнительным поиском по профору (приклеенной
   * слева частице, например ה в «הספר»); значение — сам профор.
   * Отсутствует у строк точного совпадения.
   */
  via_prefix?: string;
  /**
   * Предлоги глагола (только canonical с заполненным general.prepositions);
   * null — не заполнено / не глагол.
   */
  prepositions: PrepositionEntry[] | null;
}

export interface Dictionary {
  /**
   * Поиск форм по полю no_nikud (точное совпадение после нормализации).
   * Реализация обязана принимать запрос как с огласовками, так и без —
   * никкуд снимается перед обращением к данным.
   *
   * Дополнительно: если запрос начинается с профора (ה, ב/מ/ל, ш/כш),
   * ищется и остаток без него; строки с частью речи, допускающей этот
   * профор, добавляются к результату с полем via_prefix (см. prefixes.ts).
   */
  searchByNoNikud(query: string): Promise<FormRow[]>;

  /**
   * Все формы одного слова (страницы): строки, у которых canonical
   * равен заданному, в порядке их появления на странице.
   */
  searchByCanonical(canonical: string): Promise<FormRow[]>;
}
